#!/usr/bin/env node
// Evaluates a task's output against requirements fixed at planning time.
//
//   plan <plan.md> --category <id>   write the plan's ## Evaluation section and
//                                    one [eval:<kpi>] case per KPI
//   check <plan.md> [--category id]  is the section complete and untouched?
//   suggest <spec.md>                which category fits the spec best
//
// The KPIs come from the evaluating-outputs skill (see evaluation-registry.mjs).
// Thresholds are resolved when the section is generated and written into the
// plan, so the plan's approval covers them and a later registry change never
// moves the goalposts of an approved plan.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { isAbsolute, relative, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

import { EvaluationError, formatThreshold, loadRegistry, REGISTRY_DIR, resolveCategory } from './evaluation-registry.mjs';

export const EVALUATIONS_DIR = 'context/tasks/evaluations';
const BEGIN = '<!-- evaluation:begin — generated by `node .claude/tools/evaluation.mjs plan`; edit Override:/NA: lines above, then rerun -->';
const END = '<!-- evaluation:end -->';
const TABLE_HEAD = ['| Dimension | KPI | Metric | Threshold | Verifier | Evidence |', '| --- | --- | --- | --- | --- | --- |'];
const RERUN = 'rerun `evaluation.mjs plan`';
const OVERRIDE = /^Override:\s+(\S+)\s+(<=|>=|==)\s+(-?\d+(?:\.\d+)?)(?:\s+([^\s—]+))?\s+—\s+(\S.*)$/;
const OVERRIDE_NO_REASON = /^Override:\s+(\S+)\s+(<=|>=|==)\s+(-?\d+(?:\.\d+)?)(?:\s+(\S+))?\s*$/;
const NA = /^NA:\s+(\S+)\s+—\s+(\S.*)$/;
const ROW = /^\| (\S+) \| (\S+) \| (.+?) \| (signed|(?:<=|>=|==) -?\d+(?:\.\d+)? \S+) \| (agent|human|both) \| (measured|signed) \|$/;
const APPLIED = /^Applied: (\S+) (.+?) → (.+?) \((project|task): (.*)\)$/;
const NA_LINE = /^- (\S+)(?: \/ (\S+))?: n\/a(?: \((project|task)\))? — (.*)$/;
const EVAL_TAG = /\[eval:([^\]\s]+)\]/;

export const sha = (text) => createHash('sha256').update(text).digest('hex').slice(0, 16);
const fail = (message) => {
  throw new EvaluationError(message);
};

export function projectFile(root, path) {
  const target = resolve(root, path);
  const rel = relative(resolve(root), target);
  if (isAbsolute(path) || rel === '..' || rel.startsWith(`..${sep}`)) fail(`${path} must be inside the project`);
  if (!existsSync(target)) fail(`${path} does not exist`);
  return target;
}

// ------------------------------------------------------------------ markdown

const toLines = (text) => text.replace(/\n+$/, '').split('\n');
const fromLines = (lines) => `${lines.join('\n')}\n`;

// `## ` headings outside code fences, so a plan may quote an example section.
function headings(lines) {
  const found = [];
  let fenced = false;
  lines.forEach((line, index) => {
    if (/^\s*```/.test(line)) fenced = !fenced;
    else if (!fenced && /^#{1,2}\s/.test(line)) found.push({ index, title: line.replace(/^#{1,2}\s+/, '').trim(), level: line.startsWith('## ') ? 2 : 1 });
  });
  return found;
}

function sectionRange(lines, title) {
  const all = headings(lines);
  const at = all.findIndex((h) => h.level === 2 && h.title === title);
  if (at < 0) return null;
  return { start: all[at].index, end: all[at + 1]?.index ?? lines.length };
}

const trimBlank = (lines) => {
  let a = 0;
  let b = lines.length;
  while (a < b && !lines[a].trim()) a++;
  while (b > a && !lines[b - 1].trim()) b--;
  return lines.slice(a, b);
};

function replaceSection(lines, title, body, { before } = {}) {
  const range = sectionRange(lines, title);
  const block = (atEnd) => [`## ${title}`, '', ...body, ...(atEnd ? [] : [''])];
  if (range) return [...lines.slice(0, range.start), ...block(range.end >= lines.length), ...lines.slice(range.end)];
  const anchor = before ? sectionRange(lines, before) : null;
  if (anchor) return [...lines.slice(0, anchor.start), ...block(false), ...lines.slice(anchor.start)];
  return [...trimBlank(lines), '', ...block(true)];
}

// ------------------------------------------------------------------ the section

function parseUserLines(lines) {
  const overrides = [];
  const naLines = [];
  const problems = [];
  for (const line of lines) {
    if (line.startsWith('Override:')) {
      const m = OVERRIDE.exec(line);
      if (m) overrides.push({ id: m[1], op: m[2], value: Number(m[3]), unit: m[4], reason: m[5].trim() });
      else if (OVERRIDE_NO_REASON.test(line)) problems.push(`Override: ${OVERRIDE_NO_REASON.exec(line)[1]} needs a reason after —`);
      else problems.push(`"${line}" must read "Override: <kpi-id> <op> <value> [unit] — <reason>"`);
    } else if (line.startsWith('NA:')) {
      const m = NA.exec(line);
      if (m) naLines.push({ id: m[1], reason: m[2].trim() });
      else problems.push(`"${line}" must read "NA: <kpi-id> — <reason>"`);
    }
  }
  return { overrides, naLines, userProblems: problems };
}

const rowText = (k) => `| ${k.dimension} | ${k.id} | ${String(k.metric).replace(/\|/g, '/')} | ${formatThreshold(k)} | ${k.verifier} | ${k.evidence} |`;
const naText = (n) => (n.id ? `- ${n.dimension} / ${n.id}: n/a (${n.source}) — ${n.reason}` : `- ${n.dimension}: n/a — ${n.reason}`);
const appliedText = (a) => `Applied: ${a.id} ${a.from} → ${a.to} (${a.source}: ${a.reason})`;
const generatedHash = (category, rows, nas, applied) => sha([category, ...rows, ...nas, ...applied].join('\n'));

function generatedBlock(resolved) {
  const rows = resolved.kpis.map(rowText);
  const nas = resolved.na.map(naText);
  const applied = resolved.applied.map(appliedText);
  return [
    BEGIN,
    `Category: ${resolved.category}`,
    `Dimensions: v${resolved.version} (sha ${generatedHash(resolved.category, rows, nas, applied)})`,
    '',
    ...TABLE_HEAD,
    ...rows,
    ...(nas.length ? ['', ...nas] : []),
    ...(applied.length ? ['', ...applied] : []),
    END,
  ];
}

function parseRow(line) {
  const m = ROW.exec(line);
  if (!m) return null;
  const [, dimension, id, metric, threshold, verifier, evidence] = m;
  const [op, value, unit] = threshold === 'signed' ? ['signed', null, null] : threshold.split(' ');
  return { dimension, id, metric, op, value: value === null ? null : Number(value), unit, verifier, evidence };
}

export function parseEvaluation(planText) {
  const lines = toLines(planText);
  const range = sectionRange(lines, 'Evaluation');
  if (!range) return null;
  const section = lines.slice(range.start + 1, range.end);
  const begin = section.indexOf(BEGIN);
  const end = section.indexOf(END);
  const user = parseUserLines(begin < 0 ? section : section.slice(0, begin));
  const generated = begin >= 0 && end > begin ? section.slice(begin + 1, end) : null;
  const casesRange = sectionRange(lines, 'Test Cases');
  const cases = new Map();
  for (const line of casesRange ? lines.slice(casesRange.start + 1, casesRange.end) : []) {
    const tag = EVAL_TAG.exec(line);
    if (tag) cases.set(tag[1], line);
  }
  const parsed = { category: null, version: null, hash: null, kpis: [], na: [], applied: [], overrides: user.overrides, naLines: user.naLines, userProblems: user.userProblems, cases, generated: Boolean(generated), edited: false };
  if (!generated) return parsed;
  const rows = [];
  const nas = [];
  const applied = [];
  for (const line of generated) {
    const category = /^Category: (\S+)$/.exec(line);
    const dims = /^Dimensions: v(\d+) \(sha ([0-9a-f]+)\)$/.exec(line);
    if (category) parsed.category = category[1];
    else if (dims) [parsed.version, parsed.hash] = [Number(dims[1]), dims[2]];
    else if (TABLE_HEAD.includes(line) || !line.trim()) continue;
    else if (line.startsWith('|')) {
      rows.push(line);
      const row = parseRow(line);
      if (row) parsed.kpis.push(row);
      else parsed.edited = true;
    } else if (NA_LINE.test(line)) {
      nas.push(line);
      const [, dimension, id, source, reason] = NA_LINE.exec(line);
      parsed.na.push(id ? { dimension, id, source, reason } : { dimension, reason });
    } else if (APPLIED.test(line)) {
      applied.push(line);
      const [, id, from, to, source, reason] = APPLIED.exec(line);
      parsed.applied.push({ id, from, to, source, reason });
    } else parsed.edited = true;
  }
  if (parsed.hash !== generatedHash(parsed.category, rows, nas, applied)) parsed.edited = true;
  return parsed;
}

function kpiIdsOf(registry, category) {
  return Object.values(registry.categories[category]?.dimensions ?? {}).flatMap((d) => (d.kpis ?? []).map((k) => k.id));
}

function userLineProblems(registry, category, { overrides, naLines, userProblems }) {
  const problems = [...userProblems];
  const known = new Set(kpiIdsOf(registry, category));
  for (const o of overrides) if (!known.has(o.id)) problems.push(`Override: ${o.id} is not a KPI of ${category}`);
  for (const n of naLines) if (!known.has(n.id)) problems.push(`NA: ${n.id} is not a KPI of ${category}`);
  return problems;
}

export function writePlanEvaluation(root, planPath, categoryIds, { registry = loadRegistry({ root }) } = {}) {
  if (categoryIds.length !== 1) fail('a task is atomic: split it into one task per category (one --category per plan)');
  const [category] = categoryIds;
  const file = projectFile(root, planPath);
  let lines = toLines(readFileSync(file, 'utf8'));
  const range = sectionRange(lines, 'Evaluation');
  const section = range ? lines.slice(range.start + 1, range.end) : [];
  const begin = section.indexOf(BEGIN);
  const userLines = trimBlank(begin < 0 ? section : section.slice(0, begin));
  const user = parseUserLines(userLines);
  if (!registry.categories[category]) resolveCategory(registry, category);
  const problems = userLineProblems(registry, category, user);
  if (problems.length) fail(`${planPath}: ${problems.join('; ')}`);
  const resolved = resolveCategory(registry, category, { overrides: user.overrides, na: user.naLines });

  lines = replaceSection(lines, 'Evaluation', [...userLines, ...(userLines.length ? [''] : []), ...generatedBlock(resolved)], { before: 'Test Strategy' });
  const cases = sectionRange(lines, 'Test Cases');
  const kept = cases ? trimBlank(lines.slice(cases.start + 1, cases.end).filter((l) => !EVAL_TAG.test(l))) : [];
  lines = replaceSection(lines, 'Test Cases', [...kept, ...resolved.kpis.map((k) => `- ${k.case} [eval:${k.id}]`)]);
  writeFileSync(file, fromLines(lines));
  return parseEvaluation(fromLines(lines));
}

export function checkPlan(root, planPath, { category, registry = loadRegistry({ root }) } = {}) {
  const parsed = parseEvaluation(readFileSync(projectFile(root, planPath), 'utf8'));
  const rerun = `run \`node .claude/tools/evaluation.mjs plan ${planPath} --category ${category ?? '<id>'}\``;
  if (!parsed) return { problems: [`no ## Evaluation section; ${rerun}`], notes: [], parsed };
  if (!parsed.generated) return { problems: [`## Evaluation has no generated part; ${rerun}`], notes: [], parsed };
  const problems = [];
  const notes = [];
  if (parsed.edited) problems.push(`the generated Evaluation section was edited by hand; ${RERUN}`);
  if (category && parsed.category !== category) problems.push(`Category: ${parsed.category} in the plan, but the task says ${category}`);
  if (!registry.categories[parsed.category]) {
    problems.push(`unknown category '${parsed.category}'; available: ${Object.keys(registry.categories).sort().join(', ')}`);
    return { problems, notes, parsed };
  }
  problems.push(...userLineProblems(registry, parsed.category, parsed));
  const task = (list) => list.filter((x) => x.source === 'task');
  const appliedNow = task(parsed.applied).map((a) => `${a.id} ${a.to} ${a.reason}`).sort();
  const wanted = parsed.overrides.map((o) => `${o.id} ${formatThreshold({ ...o, unit: o.unit ?? parsed.kpis.find((k) => k.id === o.id)?.unit })} ${o.reason}`).sort();
  const naNow = task(parsed.na).map((n) => `${n.id} ${n.reason}`).sort();
  const naWanted = parsed.naLines.map((n) => `${n.id} ${n.reason}`).sort();
  if (String(appliedNow) !== String(wanted) || String(naNow) !== String(naWanted)) {
    problems.push(`Override:/NA: lines changed since the section was generated; ${RERUN}`);
  }
  for (const k of parsed.kpis) {
    if (!parsed.cases.has(k.id)) problems.push(`${k.id} has no [eval:${k.id}] case under ## Test Cases; ${RERUN}`);
  }
  if (registry.version > parsed.version) {
    notes.push(`registry v${registry.version} is newer than the plan's v${parsed.version}; rerun plan and re-approve to include it`);
  } else {
    const fresh = resolveCategory(registry, parsed.category, { overrides: parsed.overrides, na: parsed.naLines });
    if (String(fresh.kpis.map(rowText)) !== String(parsed.kpis.map(rowText))) {
      notes.push('thresholds differ from the current registry or .claude/evaluation.json; rerun plan and re-approve to adopt them');
    }
  }
  return { problems, notes, parsed };
}

export function suggestCategory(text, registry) {
  const ranked = Object.entries(registry.categories)
    .map(([category, c]) => ({
      category,
      hits: (c.match ?? []).reduce((n, word) => n + (text.match(new RegExp(`\\b${word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'gi'))?.length ?? 0), 0),
    }))
    .filter((r) => r.hits > 0)
    .sort((a, b) => b.hits - a.hits || a.category.localeCompare(b.category));
  return ranked.length ? ranked : [{ category: 'general', hits: 0 }];
}

// ------------------------------------------------------------------ CLI

const USAGE = `evaluation: requirements fixed at planning time, scored on the task's output

Usage
  node .claude/tools/evaluation.mjs suggest <spec.md>
  node .claude/tools/evaluation.mjs plan <plan.md> --category <id>
  node .claude/tools/evaluation.mjs check <plan.md> [--category <id>]

A task is atomic: one category per plan. Categories and KPIs live in
.claude/skills/evaluating-outputs/ (see its SKILL.md).`;

function flags(args, name) {
  const values = [];
  const rest = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === name) values.push(args[++i]);
    else rest.push(args[i]);
  }
  return { values, rest };
}

function dispatch(command, args, { root, log, registry }) {
  if (command === 'suggest') {
    const [spec] = args;
    if (!spec) fail('usage: suggest <spec.md>');
    for (const s of suggestCategory(readFileSync(projectFile(root, spec), 'utf8'), registry())) log(`${s.category} (${s.hits} keyword hit${s.hits === 1 ? '' : 's'})`);
    return 0;
  }
  if (command === 'plan') {
    const { values, rest } = flags(args, '--category');
    if (!rest[0] || values.length === 0) fail('usage: plan <plan.md> --category <id>');
    const parsed = writePlanEvaluation(root, rest[0], values, { registry: registry() });
    log(`wrote ## Evaluation (${parsed.category}, ${parsed.kpis.length} KPIs) and ${parsed.kpis.length} [eval:] cases to ${rest[0]}`);
    return 0;
  }
  if (command === 'check') {
    const { values, rest } = flags(args, '--category');
    if (!rest[0]) fail('usage: check <plan.md> [--category <id>]');
    const { problems, notes } = checkPlan(root, rest[0], { category: values[0], registry: registry() });
    for (const p of problems) log(`- ${p}`);
    for (const n of notes) log(`note: ${n}`);
    log(problems.length ? 'NOT READY' : 'READY');
    return problems.length ? 1 : 0;
  }
  log(USAGE);
  return command && !['help', '--help', '-h'].includes(command) ? 1 : 0;
}

export function run(argv, { root = process.cwd(), log = console.log, error = console.error, registryDir = REGISTRY_DIR } = {}) {
  const [command, ...args] = argv;
  let cached;
  const registry = () => (cached ??= loadRegistry({ dir: registryDir, root }));
  try {
    return dispatch(command, args, { root, log, registry });
  } catch (e) {
    if (!(e instanceof EvaluationError)) throw e;
    error(`evaluation: ${e.message}`);
    return 1;
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.exitCode = run(process.argv.slice(2), { root: process.env.CLAUDE_PROJECT_DIR || process.cwd() });
}

