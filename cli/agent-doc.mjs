// Renders AGENT.md from the interview answers. The section headings come
// from the package's AGENT.md template, so that file stays the single
// source for the document's structure.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { hookCatalog, PACKAGE_ROOT, skillCatalog } from './catalog.mjs';
import { LABELS } from './questions.mjs';

export const GENERATED_MARK = '<!-- Generated by ai-stones. Edit freely: `stones init` will not overwrite your edits. -->';

const key = (heading) => heading.toLowerCase().replace(/[^a-z]+/g, ' ').trim();
const bullets = (items) => items.filter(Boolean).map((i) => `- ${i}`).join('\n');
const docLink = (skill) => `[${skill.title}](.claude/skills/${skill.main})`;
const docSuffix = (d) => (d ? ` (${docLink(d)})` : '');

function renderStackAndLayout(answers, stack) {
  const layout = Object.entries(answers.stack.layout ?? {})
    .map(([dir, what]) => (what ? `\`${dir}/\` — ${what}` : `\`${dir}/\``));

  const items = [
    answers.stack.technologies.length && `Technologies: ${answers.stack.technologies.join(', ')}`,
    stack.packageManagers.length && `Package manager: ${stack.packageManagers.join(', ')}`,
    stack.monorepo && `Monorepo: ${stack.monorepo}`,
    stack.tools.length && `Tooling: ${stack.tools.join(', ')}`,
  ];

  return [
    bullets(items),
    layout.length ? `\nLayout:\n\n${bullets(layout)}` : '',
  ].join('\n').trim();
}

function renderPatterns(answers, docs) {
  if (!answers.patterns.length) return '_No specific patterns._';
  const list = answers.patterns
    .map((id) => docs.get(id))
    .filter(Boolean)
    .map((d) => `${docLink(d)} — ${d.lead}`);
  return `Follow these patterns; load the skill before applying one.\n\n${bullets(list)}`;
}

function renderAccess(answers, has) {
  return bullets([
    answers.security.secrets && `Secrets: ${answers.security.secrets}`,
    answers.security.auth && `Authentication: ${answers.security.auth}`,
    has('access_guard') && 'Never read `.env*` files (except `.env.example`) or anything under `private/`; the access guard hook blocks it.',
    has('access_guard') && 'Never `git push`; a human pushes.',
    answers.security.notes,
  ]);
}

function renderConventions(answers, stack, { has, doc }) {
  const commitMsg = answers.conventions.commits === 'conventional'
    ? 'Commits follow Conventional Commits: `feat: …`, `fix: …`, `docs: …`, `refactor: …`, `test: …`.'
    : 'Commits use a short imperative summary line.';

  return bullets([
    commitMsg,
    has('naming') && `File names follow the project's existing style per language; the naming hook rejects others${docSuffix(doc('naming-files'))}.`,
    has('format') && stack.formatters.length && `Formatting is applied after every edit with ${stack.formatters.join(', ')}; do not hand-format.`,
    doc('defining-types') && `Types: ${docLink(doc('defining-types'))}.`,
    doc('creating-files-and-modules') && `Creating files: ${docLink(doc('creating-files-and-modules'))}.`,
    answers.conventions.notes,
  ]);
}

function renderWorkflow(answers, stack, { doc }) {
  const commands = Object.entries(answers.workflow.commands).filter(([, c]) => c);
  const branching = LABELS.branching[answers.workflow.branching];

  const commandLines = commands.length
    ? `Commands:\n\n${commands.map(([task, c]) => `- ${task}: \`${c}\``).join('\n')}`
    : '';

  const workflowBullets = bullets([
    branching && `Branching: ${branching.label} — ${branching.hint}; default branch \`${stack.defaultBranch}\`.`,
    answers.workflow.tdd && `Work test-first: write a failing test, make it pass, refactor${docSuffix(doc('test-first-development'))}.`,
    doc('writing-tests') && `Testing strategy: ${docLink(doc('writing-tests'))}.`,
    doc('creating-branches') && `Branches: ${docLink(doc('creating-branches'))}.`,
    doc('opening-pull-requests') && `Pull requests: ${docLink(doc('opening-pull-requests'))}.`,
    doc('four-d-engineering') && `Scope, brief, verify and report non-trivial work with ${docLink(doc('four-d-engineering'))}.`,
    commands.some(([t]) => t === 'test') && 'Run the tests before saying a change is done, and report failures as they are.',
    commands.length && 'Run every quality gate with `node .claude/tools/quality-check.mjs` (`--only test`, `--fail-fast`); it records the result for the PR.',
    'Open pull requests with `node .claude/tools/create-pr.mjs draft > .claude/pr.md`, fill in its TODOs, then `create-pr.mjs create --body-file .claude/pr.md` once the branch is pushed.',
    'When a change touches documented behavior, run `node .claude/tools/sync-docs.mjs` and fix what it reports in the same change.',
    'Check what matters now with `node .claude/tools/roadmap.mjs show`; record decisions with `roadmap.mjs decide "<decision>" "<why>"`.',
    'Before adding a dependency, check what the project already declares with `node .claude/tools/list-packages.mjs` (`--grep <name>`, `--prod`, `--json`) and reuse a package that does the job.',
    'When resuming work in a branch or worktree, read its history first with `node .claude/tools/worktree-history.mjs show` (`list` for every worktree).',
    'Leave context on commits with `node .claude/tools/git-comments.mjs set|append <rev> <text>` (why it exists, what was verified, what is left); read it with `get` or `list`. Comments are git notes and never change the commit.',
  ]);

  return [commandLines, workflowBullets].filter(Boolean).join('\n\n');
}

function renderGuardrails(answers, stack, { has, doc, hooks }) {
  const hookBullets = answers.install.hooks
    .map((id) => hooks.get(id))
    .filter(Boolean)
    .map((h) => `\`${h.id}\` hook: ${h.hint}.`);

  const migrationGen = stack.migrations?.generate || "your ORM's migration generator";

  return bullets([
    ...hookBullets,
    has('atomicity') && `Danger zones (db, packages, network) go on their own \`db/\`, \`deps/\`, \`net/\` branch and PR with a spec in \`.claude/danger/\`; never mix them with other changes; generate migrations with \`${migrationGen}\`${docSuffix(doc('atomic-changes'))}.`,
    answers.install.devcontainer && `Dev container: .devcontainer/ (\`${answers.install.devcontainer}\`). Edit .devcontainer/Dockerfile only — devcontainer.json is generated from it.`,
    has('graph') && 'When the graph hook asks for a file summary, add it to the OpenSpec `files.md` it names (see `.claude/graph/README.md`).',
    answers.guardrails.notes,
  ]) || '_None yet._';
}

function sections(answers, stack) {
  const docs = new Map(skillCatalog().map((s) => [s.id, s]));
  const hooks = new Map(hookCatalog().map((h) => [h.id, h]));
  const installed = new Set(answers.install.hooks);
  const ctx = {
    docs,
    hooks,
    has: (id) => installed.has(id),
    doc: (id) => (answers.install.skills.includes(id) && docs.get(id)) || undefined,
  };
  const arch = LABELS.architecture[answers.architecture.style];

  return {
    project: `**${answers.project.name}**`,
    'what this is': answers.project.description || '_Describe what the project is and who it is for._',
    'stack and layout': renderStackAndLayout(answers, stack),
    architecture: [
      arch ? `${arch.label}: ${arch.hint}.` : '',
      answers.architecture.notes,
    ].filter(Boolean).join('\n\n'),
    'design pattern': renderPatterns(answers, docs),
    'access and security': renderAccess(answers, ctx.has),
    conventions: renderConventions(answers, stack, ctx),
    workflow: renderWorkflow(answers, stack, ctx),
    guardrails: renderGuardrails(answers, stack, ctx),
    roadmap: 'Plans and milestones live in [ROADMAP.md](ROADMAP.md); read it when choosing what to work on. '
      + 'Create or revise it with `/roadmap` in Claude Code or `npx ai-stones roadmap`.',
  };
}

export function renderAgentDoc(answers, stack, root = PACKAGE_ROOT) {
  const template = readFileSync(join(root, 'AGENT.md'), 'utf8');
  const headings = [...template.matchAll(/^##\s+(.+)$/gm)].map((m) => m[1].trim());
  const content = sections(answers, stack);
  const out = [GENERATED_MARK, ''];
  for (const heading of headings) {
    out.push(`## ${heading}`, '', content[key(heading)] || '_TODO_', '');
  }
  return out.join('\n');
}
